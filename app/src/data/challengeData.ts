export function getDeedById(id: number): Deed | undefined {
    return ALL_DEEDS.find(d => d.id === id);
}

// Pick a daily challenge based on the current date (deterministic per day)
export function getDailyChallengeId(): number {
    const today = new Date();
    const seed = today.getFullYear() * 10000 + (today.getMonth() + 1) * 100 + today.getDate();
    return ALL_DEEDS[seed % ALL_DEEDS.length].id;
}
